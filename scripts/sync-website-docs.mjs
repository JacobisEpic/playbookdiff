// Mirrors the repository's documentation into the website so `/docs` renders
// the same Markdown that lives in `docs/`.
//
//   node scripts/sync-website-docs.mjs           writes the mirror
//   node scripts/sync-website-docs.mjs --check   fails if it is stale
//
// The mirror exists because the website builds from its own directory with its
// own lockfile, so the deployment cannot rely on reaching outside it. It is
// generated, never hand-edited: `docs/` stays the single source of truth and
// `website/tests/docs.test.mjs` fails the build if the two diverge.

import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const repositoryRoot = path.resolve(import.meta.dirname, "..");
const source = path.join(repositoryRoot, "docs");
const mirror = path.join(repositoryRoot, "website", "content", "docs");

const notice = `<!--
Generated by scripts/sync-website-docs.mjs. Do not edit these files.

The documentation in the repository's docs/ directory is the source of truth.
Change it there, then run \`pnpm website:sync\`.
-->
`;

async function markdownFiles() {
  const entries = await readdir(source, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
    .map((entry) => path.relative(source, path.join(entry.parentPath, entry.name)))
    .sort();
}

const files = await markdownFiles();
const check = process.argv.includes("--check");
const stale = [];

if (!check) {
  await rm(mirror, { recursive: true, force: true });
  await mkdir(mirror, { recursive: true });
  await writeFile(path.join(mirror, "README.md"), notice);
}

for (const file of files) {
  const content = await readFile(path.join(source, file), "utf8");
  const destination = path.join(mirror, file);

  if (check) {
    const current = await readFile(destination, "utf8").catch(() => null);
    if (current !== content) stale.push(file);
    continue;
  }

  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, content);
}

if (check) {
  // A document removed from docs/ must not linger in the mirror either.
  const mirrored = await readdir(mirror, { recursive: true, withFileTypes: true });
  for (const entry of mirrored) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
    const file = path.relative(mirror, path.join(entry.parentPath, entry.name));
    if (file !== "README.md" && !files.includes(file)) stale.push(`${file} (removed from docs/)`);
  }

  if (stale.length > 0) {
    console.error(
      `website/content/docs is stale for: ${stale.join(", ")}. Run \`pnpm website:sync\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`website/content/docs matches docs/ (${files.length} files).`);
} else {
  console.log(`Mirrored ${files.length} documents into website/content/docs.`);
}
